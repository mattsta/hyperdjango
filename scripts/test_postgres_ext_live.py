async def test_constraints(db):
    print("\n--- Constraints (live) ---")
    tbl = f"test_excl{SUFFIX}"
    try:
        # ExclusionConstraint with btree_gist
        ec = ExclusionConstraint(
            name=f"no_overlap{SUFFIX}",
            expressions=[("room", "="), ("period", "&&")],
            index_type="GIST",
        )

        await db.execute(f"""
            CREATE TABLE {tbl} (
                id SERIAL PRIMARY KEY,
                room INTEGER NOT NULL,
                period int4range NOT NULL,
                {ec.as_sql()}
            )
        """)

        # Insert non-overlapping
        await db.execute(
            f"INSERT INTO {tbl} (room, period) VALUES ($1, $2)", 1, "[1,5)"
        )
        await db.execute(
            f"INSERT INTO {tbl} (room, period) VALUES ($1, $2)", 1, "[5,10)"
        )
        await db.execute(
            f"INSERT INTO {tbl} (room, period) VALUES ($1, $2)", 2, "[1,10)"
        )

        rows = await db.query(f"SELECT * FROM {tbl} ORDER BY id")
        test("non-overlapping inserts", len(rows), 3)

        # Overlapping should fail
        try:
            await db.execute(
                f"INSERT INTO {tbl} (room, period) VALUES ($1, $2)", 1, "[3,7)"
            )
            test("exclusion constraint violated", False, True)
        except Exception:
            test("exclusion constraint enforced", True, True)

        # Different room, same period is OK
        await db.execute(
            f"INSERT INTO {tbl} (room, period) VALUES ($1, $2)", 3, "[1,5)"
        )
        rows = await db.query(f"SELECT * FROM {tbl} ORDER BY id")
        test("different room same period OK", len(rows), 4)

        # Conditional exclusion constraint
        tbl2 = f"test_excl_cond{SUFFIX}"
        ec2 = ExclusionConstraint(
            name=f"no_overlap_active{SUFFIX}",
            expressions=[("room", "="), ("period", "&&")],
            condition="cancelled = false",
        )
        await db.execute(f"""
            CREATE TABLE {tbl2} (
                id SERIAL PRIMARY KEY,
                room INTEGER NOT NULL,
                period int4range NOT NULL,
                cancelled BOOLEAN NOT NULL DEFAULT false,
                {ec2.as_sql()}
            )
        """)

        await db.execute(
            f"INSERT INTO {tbl2} (room, period) VALUES ($1, $2)", 1, "[1,10)"
        )
        # Overlapping but cancelled should be allowed
        await db.execute(
            f"INSERT INTO {tbl2} (room, period, cancelled) VALUES ($1, $2, $3)",
            1,
            "[5,15)",
            True,
        )
        rows = await db.query(f"SELECT * FROM {tbl2}")
        test("conditional exclusion allows cancelled", len(rows), 2)

    finally:
        await db.execute(f"DROP TABLE IF EXISTS {tbl}")
        tbl2 = f"test_excl_cond{SUFFIX}"
        await db.execute(f"DROP TABLE IF EXISTS {tbl2}")


