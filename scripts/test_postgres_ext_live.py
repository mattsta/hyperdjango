async def test_trigrams(db):
    print("\n--- Trigram Similarity (live) ---")
    tbl = f"test_trigram{SUFFIX}"
    try:
        await db.execute(f"""
            CREATE TABLE {tbl} (
                id SERIAL PRIMARY KEY,
                name TEXT NOT NULL
            )
        """)

        names = [
            "PostgreSQL",
            "SQLite",
            "DuckDB",
            "Firebird",
            "Datalog",
            "Datomic",
            "Dolt",
            "Etcd",
            "Foundation",
            "Ignite",
        ]
        for name in names:
            await db.execute(f"INSERT INTO {tbl} (name) VALUES ($1)", name)

        # similarity() function
        row = await db.query_one(
            "SELECT similarity($1, $2) AS sim", "PostgreSQL", "Postgres"
        )
        test_true("similarity > 0.3", row["sim"] > 0.3, f"sim={row['sim']}")

        # word_similarity() function
        row = await db.query_one(
            "SELECT word_similarity($1, $2) AS sim", "SQL", "PostgreSQL database"
        )
        test_true("word_similarity > 0", row["sim"] > 0, f"sim={row['sim']}")

        # trigram_similar (% operator) -- fuzzy match
        rows = await db.query(
            f"SELECT name FROM {tbl} WHERE name % $1 ORDER BY similarity(name, $1) DESC",
            "Postgres",
        )
        test_true(
            "trigram % finds PostgreSQL",
            len(rows) >= 1 and rows[0]["name"] == "PostgreSQL",
            f"got {[r['name'] for r in rows]}",
        )

        # word_similarity function
        row = await db.query_one(
            "SELECT word_similarity($1, $2) AS sim",
            "Postgres",
            "PostgreSQL",
        )
        test_true(
            "word_similarity Postgres/PostgreSQL > 0.5",
            row["sim"] > 0.5,
            f"got {row['sim']}",
        )

        # <-> distance operator
        row = await db.query_one(
            f"SELECT name, (name <-> $1) AS dist FROM {tbl} ORDER BY dist LIMIT 1",
            "Postgres",
        )
        test("closest to 'Postgres'", row["name"], "PostgreSQL")
        test_true("distance < 1", row["dist"] < 1.0, f"dist={row['dist']}")

        # GIN index with gin_trgm_ops
        idx_name = f"idx_trgm{SUFFIX}"
        await db.execute(
            f'CREATE INDEX "{idx_name}" ON {tbl} USING GIN (name gin_trgm_ops)'
        )
        row = await db.query_one(
            "SELECT indexname FROM pg_indexes WHERE tablename = $1 AND indexname = $2",
            tbl,
            idx_name,
        )
        test("gin trgm index exists", row["indexname"], idx_name)

        # GiST index with gist_trgm_ops
        idx_name2 = f"idx_trgm_gist{SUFFIX}"
        await db.execute(
            f'CREATE INDEX "{idx_name2}" ON {tbl} USING GiST (name gist_trgm_ops)'
        )
        row = await db.query_one(
            "SELECT indexname FROM pg_indexes WHERE tablename = $1 AND indexname = $2",
            tbl,
            idx_name2,
        )
        test("gist trgm index exists", row["indexname"], idx_name2)

        # Fuzzy search: "postgre" finds "PostgreSQL"
        rows = await db.query(
            f"SELECT name FROM {tbl} WHERE similarity(name, $1) > 0.2 ORDER BY similarity(name, $1) DESC",
            "postgre",
        )
        test_true(
            "fuzzy 'postgre' finds PostgreSQL",
            len(rows) >= 1 and rows[0]["name"] == "PostgreSQL",
            f"got {[r['name'] for r in rows]}",
        )

        # Similarity ordering
        rows = await db.query(
            f"SELECT name, similarity(name, $1) AS sim FROM {tbl} WHERE similarity(name, $1) > 0.1 ORDER BY sim DESC LIMIT 3",
            "Datalo",
        )
        test_true(
            "similarity ordering Datalo -> Datalog first",
            len(rows) >= 1 and rows[0]["name"] == "Datalog",
            f"got {[r['name'] for r in rows]}",
        )

    finally:
        await db.execute(f"DROP TABLE IF EXISTS {tbl}")


