async def test_jsonb(db):
    print("\n--- JSONB (live) ---")
    tbl = f"test_jsonb{SUFFIX}"
    try:
        await db.execute(f"""
            CREATE TABLE {tbl} (
                id SERIAL PRIMARY KEY,
                data JSONB NOT NULL
            )
        """)

        # Insert JSONB data
        docs = [
            {
                "name": "Alice",
                "age": 30,
                "tags": ["admin", "user"],
                "address": {"city": "NYC"},
            },
            {"name": "Bob", "age": 25, "tags": ["user"], "address": {"city": "LA"}},
            {
                "name": "Charlie",
                "age": 35,
                "tags": ["admin"],
                "address": {"city": "NYC"},
            },
        ]
        for doc in docs:
            await db.execute(f"INSERT INTO {tbl} (data) VALUES ($1)", json.dumps(doc))

        # Containment (@>)
        rows = await db.query(
            f"""SELECT id FROM {tbl} WHERE data @> $1 ORDER BY id""",
            json.dumps({"address": {"city": "NYC"}}),
        )
        test("jsonb containment @>", [r["id"] for r in rows], [1, 3])

        # Key existence (?)
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE data ? $1 ORDER BY id", "name"
        )
        test("jsonb key existence ?", [r["id"] for r in rows], [1, 2, 3])

        # Path query (->>)
        rows = await db.query(
            f"SELECT data->>'name' AS name FROM {tbl} WHERE (data->>'age')::int > $1 ORDER BY data->>'name'",
            28,
        )
        test("jsonb ->> path query", [r["name"] for r in rows], ["Alice", "Charlie"])

        # Nested path (#>>)
        path_literal = "'{address,city}'"
        rows = await db.query(
            f"SELECT data#>>{path_literal} AS city FROM {tbl} ORDER BY id"
        )
        test("jsonb #>> nested path", [r["city"] for r in rows], ["NYC", "LA", "NYC"])

        # Array containment within JSONB
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE data->'tags' @> $1 ORDER BY id",
            json.dumps(["admin"]),
        )
        test("jsonb array containment", [r["id"] for r in rows], [1, 3])

        # GIN index on JSONB
        jsonb_idx = f"idx_jsonb{SUFFIX}"
        await db.execute(f'CREATE INDEX "{jsonb_idx}" ON {tbl} USING GIN (data)')
        row = await db.query_one(
            "SELECT indexname FROM pg_indexes WHERE tablename = $1 AND indexname = $2",
            tbl,
            jsonb_idx,
        )
        test("gin jsonb index exists", row["indexname"], jsonb_idx)

        # jsonb_path_query (PG12+)
        tags_literal = '\'{"tags": ["user"]}\''
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE data @> {tags_literal}::jsonb ORDER BY id"
        )
        test("jsonb tags contains user", [r["id"] for r in rows], [1, 2])

        # JSONB concatenation (||)
        row = await db.query_one(
            f"SELECT data || $1 AS merged FROM {tbl} WHERE id = 1",
            json.dumps({"role": "superadmin"}),
        )
        merged = row["merged"]
        if isinstance(merged, str):
            merged = json.loads(merged)
        test_true("jsonb merge has role", merged.get("role") == "superadmin")
        test_true("jsonb merge keeps name", merged.get("name") == "Alice")

        # JSONB key deletion (-)
        row = await db.query_one(
            f"SELECT data - 'age' AS trimmed FROM {tbl} WHERE id = 1"
        )
        trimmed = row["trimmed"]
        if isinstance(trimmed, str):
            trimmed = json.loads(trimmed)
        test_true("jsonb delete key", "age" not in trimmed)
        test_true("jsonb delete keeps others", "name" in trimmed)

        # jsonb_typeof
        row = await db.query_one(
            f"SELECT jsonb_typeof(data->'age') AS t FROM {tbl} WHERE id = 1"
        )
        test("jsonb_typeof", row["t"], "number")

    finally:
        await db.execute(f"DROP TABLE IF EXISTS {tbl}")


