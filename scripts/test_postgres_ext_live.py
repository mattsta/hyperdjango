async def test_aggregates(db):
    print("\n--- Aggregates (live) ---")
    tbl = f"test_agg{SUFFIX}"
    try:
        await db.execute(f"""
            CREATE TABLE {tbl} (
                id SERIAL PRIMARY KEY,
                name TEXT NOT NULL,
                category TEXT NOT NULL,
                flags INTEGER NOT NULL,
                active BOOLEAN NOT NULL
            )
        """)

        data = [
            ("Alice", "A", 6, True),
            ("Bob", "A", 3, True),
            ("Charlie", "B", 5, False),
            ("Diana", "B", 7, True),
            ("Eve", "A", 2, False),
        ]
        for name, cat, flags, active in data:
            await db.execute(
                f"INSERT INTO {tbl} (name, category, flags, active) VALUES ($1, $2, $3, $4)",
                name,
                cat,
                flags,
                active,
            )

        # array_agg
        row = await db.query_one(
            f"SELECT array_agg(name ORDER BY name) AS names FROM {tbl}"
        )
        test("array_agg", row["names"], ["Alice", "Bob", "Charlie", "Diana", "Eve"])

        # array_agg with distinct
        row = await db.query_one(
            f"SELECT array_agg(DISTINCT category ORDER BY category) AS cats FROM {tbl}"
        )
        test("array_agg distinct", row["cats"], ["A", "B"])

        # jsonb_agg
        row = await db.query_one(
            f"SELECT jsonb_agg(name ORDER BY name) AS names FROM {tbl}"
        )
        test("jsonb_agg", row["names"], ["Alice", "Bob", "Charlie", "Diana", "Eve"])

        # string_agg
        row = await db.query_one(
            f"SELECT string_agg(name, ', ' ORDER BY name) AS names FROM {tbl}"
        )
        test("string_agg", row["names"], "Alice, Bob, Charlie, Diana, Eve")

        # string_agg with custom delimiter
        row = await db.query_one(
            f"SELECT string_agg(name, ' | ' ORDER BY name) AS names FROM {tbl} WHERE category = 'A'"
        )
        test("string_agg delimiter", row["names"], "Alice | Bob | Eve")

        # bit_and
        row = await db.query_one(f"SELECT bit_and(flags) AS result FROM {tbl}")
        test("bit_and", row["result"], 6 & 3 & 5 & 7 & 2)  # 0

        # bit_or
        row = await db.query_one(f"SELECT bit_or(flags) AS result FROM {tbl}")
        test("bit_or", row["result"], 6 | 3 | 5 | 7 | 2)  # 7

        # bool_and
        row = await db.query_one(f"SELECT bool_and(active) AS result FROM {tbl}")
        test("bool_and all", row["result"], False)

        row = await db.query_one(
            f"SELECT bool_and(active) AS result FROM {tbl} WHERE category = 'B'"
        )
        test("bool_and category B", row["result"], False)

        # bool_or
        row = await db.query_one(f"SELECT bool_or(active) AS result FROM {tbl}")
        test("bool_or all", row["result"], True)

        # array_agg with filter
        row = await db.query_one(
            f"SELECT array_agg(name ORDER BY name) FILTER (WHERE active) AS names FROM {tbl}"
        )
        test("array_agg filter", row["names"], ["Alice", "Bob", "Diana"])

        # string_agg distinct
        row = await db.query_one(
            f"SELECT string_agg(DISTINCT category, ', ' ORDER BY category) AS cats FROM {tbl}"
        )
        test("string_agg distinct", row["cats"], "A, B")

        # jsonb_agg with filter
        row = await db.query_one(
            f"SELECT jsonb_agg(name ORDER BY name) FILTER (WHERE NOT active) AS names FROM {tbl}"
        )
        test("jsonb_agg filter inactive", row["names"], ["Charlie", "Eve"])

    finally:
        await db.execute(f"DROP TABLE IF EXISTS {tbl}")


