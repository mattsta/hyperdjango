async def test_array_field(db):
    print("\n--- ArrayField (live) ---")
    tbl = f"test_arrays{SUFFIX}"
    try:
        await db.execute(f"""
            CREATE TABLE {tbl} (
                id SERIAL PRIMARY KEY,
                int_arr integer[],
                txt_arr text[],
                bool_arr boolean[]
            )
        """)

        # INSERT array values
        await db.execute(
            f"INSERT INTO {tbl} (int_arr, txt_arr, bool_arr) VALUES ($1, $2, $3)",
            [1, 2, 3],
            ["hello", "world"],
            [True, False],
        )
        await db.execute(
            f"INSERT INTO {tbl} (int_arr, txt_arr, bool_arr) VALUES ($1, $2, $3)",
            [4, 5],
            ["foo"],
            [True, True],
        )
        await db.execute(
            f"INSERT INTO {tbl} (int_arr, txt_arr, bool_arr) VALUES ($1, $2, $3)",
            [1, 5, 9],
            ["bar", "baz"],
            [False, False],
        )

        # SELECT all
        rows = await db.query(f"SELECT * FROM {tbl} ORDER BY id")
        test("array insert count", len(rows), 3)

        # array_contains (@>) -- rows where int_arr contains {1, 2}
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_arr @> $1 ORDER BY id", [1, 2]
        )
        test("array_contains @>", [r["id"] for r in rows], [1])

        # array_contained_by (<@) -- rows where int_arr is subset of {1,2,3,4,5}
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_arr <@ $1 ORDER BY id", [1, 2, 3, 4, 5]
        )
        test("array_contained_by <@", [r["id"] for r in rows], [1, 2])

        # array_overlap (&&) -- rows where int_arr overlaps with {5, 9}
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_arr && $1 ORDER BY id", [5, 9]
        )
        test("array_overlap &&", [r["id"] for r in rows], [2, 3])

        # array_append
        await db.execute(
            f"UPDATE {tbl} SET int_arr = array_append(int_arr, $1) WHERE id = $2", 99, 1
        )
        row = await db.query_one(f"SELECT int_arr FROM {tbl} WHERE id = 1")
        test("array_append", row["int_arr"], [1, 2, 3, 99])

        # array_prepend
        await db.execute(
            f"UPDATE {tbl} SET int_arr = array_prepend($1, int_arr) WHERE id = $2", 0, 2
        )
        row = await db.query_one(f"SELECT int_arr FROM {tbl} WHERE id = 2")
        test("array_prepend", row["int_arr"], [0, 4, 5])

        # array_length
        row = await db.query_one(
            f"SELECT array_length(int_arr, 1) AS len FROM {tbl} WHERE id = 1"
        )
        test("array_length", row["len"], 4)

        # array indexing (1-based)
        row = await db.query_one(
            f"SELECT int_arr[1] AS first, int_arr[2] AS second FROM {tbl} WHERE id = 1"
        )
        test("array_index [1]", row["first"], 1)
        test("array_index [2]", row["second"], 2)

        # array_remove
        await db.execute(
            f"UPDATE {tbl} SET int_arr = array_remove(int_arr, $1) WHERE id = $2", 99, 1
        )
        row = await db.query_one(f"SELECT int_arr FROM {tbl} WHERE id = 1")
        test("array_remove", row["int_arr"], [1, 2, 3])

        # array_position
        row = await db.query_one(
            f"SELECT array_position(int_arr, $1) AS pos FROM {tbl} WHERE id = 3", 9
        )
        test("array_position", row["pos"], 3)

        # NULL handling in arrays
        await db.execute(f"INSERT INTO {tbl} (int_arr) VALUES ($1)", None)
        row = await db.query_one(f"SELECT int_arr FROM {tbl} WHERE id = 4")
        test("array NULL", row["int_arr"], None)

        # Empty array
        await db.execute(f"INSERT INTO {tbl} (int_arr) VALUES ($1)", [])
        row = await db.query_one(f"SELECT int_arr FROM {tbl} WHERE id = 5")
        test("empty array", row["int_arr"], [])

        # array_cat (concatenate)
        row = await db.query_one(
            "SELECT array_cat($1::integer[], $2::integer[]) AS combined",
            [1, 2],
            [3, 4],
        )
        test("array_cat", row["combined"], [1, 2, 3, 4])

        # unnest
        rows = await db.query(
            f"SELECT unnest(int_arr) AS val FROM {tbl} WHERE id = 1 ORDER BY val"
        )
        test("unnest", [r["val"] for r in rows], [1, 2, 3])

        # text array operations
        rows = await db.query(f"SELECT id FROM {tbl} WHERE txt_arr @> $1", ["hello"])
        test("text array contains", [r["id"] for r in rows], [1])

        # boolean array
        row = await db.query_one(f"SELECT bool_arr FROM {tbl} WHERE id = 2")
        test("boolean array", row["bool_arr"], [True, True])

    finally:
        await db.execute(f"DROP TABLE IF EXISTS {tbl}")


