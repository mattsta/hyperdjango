async def test_ranges(db):
    print("\n--- Range Types (live) ---")
    tbl = f"test_ranges{SUFFIX}"
    try:
        await db.execute(f"""
            CREATE TABLE {tbl} (
                id SERIAL PRIMARY KEY,
                int_range int4range,
                date_range daterange,
                num_range numrange
            )
        """)

        # Insert range values
        await db.execute(
            f"INSERT INTO {tbl} (int_range, date_range, num_range) VALUES ($1, $2, $3)",
            "[1,10)",
            "[2024-01-01,2024-06-30)",
            "[1.5,9.9)",
        )
        await db.execute(
            f"INSERT INTO {tbl} (int_range, date_range, num_range) VALUES ($1, $2, $3)",
            "[5,20)",
            "[2024-03-01,2024-12-31)",
            "[0.0,5.0)",
        )
        await db.execute(
            f"INSERT INTO {tbl} (int_range, date_range, num_range) VALUES ($1, $2, $3)",
            "[20,30)",
            "[2025-01-01,2025-06-30)",
            "[10.0,20.0)",
        )

        # int4range: contains element (@>)
        rows = await db.query(f"SELECT id FROM {tbl} WHERE int_range @> 5 ORDER BY id")
        test("int4range contains 5", [r["id"] for r in rows], [1, 2])

        rows = await db.query(f"SELECT id FROM {tbl} WHERE int_range @> 25 ORDER BY id")
        test("int4range contains 25", [r["id"] for r in rows], [3])

        # int4range: overlap (&&)
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_range && '[8,12)'::int4range ORDER BY id"
        )
        test("int4range overlap [8,12)", [r["id"] for r in rows], [1, 2])

        # int4range: adjacent (-|-)
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_range -|- '[10,15)'::int4range ORDER BY id"
        )
        test("int4range adjacent [10,15)", [r["id"] for r in rows], [1])

        # int4range: fully left of (<<)
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_range << '[25,35)'::int4range ORDER BY id"
        )
        test("int4range << [25,35)", [r["id"] for r in rows], [1, 2])

        # int4range: fully right of (>>)
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_range >> '[0,5)'::int4range ORDER BY id"
        )
        test("int4range >> [0,5)", [r["id"] for r in rows], [2, 3])

        # daterange: contains date
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE date_range @> '2024-04-15'::date ORDER BY id"
        )
        test("daterange contains 2024-04-15", [r["id"] for r in rows], [1, 2])

        # daterange: overlaps range
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE date_range && '[2024-06-01,2024-09-01)'::daterange ORDER BY id"
        )
        test("daterange overlap", [r["id"] for r in rows], [1, 2])

        # numrange: upper/lower bounds
        row = await db.query_one(
            f"SELECT lower(num_range) AS lo, upper(num_range) AS hi FROM {tbl} WHERE id = 1"
        )
        test_true(
            "numrange lower", abs(float(row["lo"]) - 1.5) < 0.01, f"lo={row['lo']}"
        )
        test_true(
            "numrange upper", abs(float(row["hi"]) - 9.9) < 0.01, f"hi={row['hi']}"
        )

        # Empty range
        await db.execute(f"INSERT INTO {tbl} (int_range) VALUES ('empty'::int4range)")
        row = await db.query_one(
            f"SELECT isempty(int_range) AS empty FROM {tbl} WHERE id = 4"
        )
        test("empty range", row["empty"], True)

        # Range contained by (<@)
        rows = await db.query(
            f"SELECT id FROM {tbl} WHERE int_range <@ '[0,35)'::int4range ORDER BY id"
        )
        test("range contained_by [0,35)", len(rows), 4)  # all rows fit in [0,35)

    finally:
        await db.execute(f"DROP TABLE IF EXISTS {tbl}")


