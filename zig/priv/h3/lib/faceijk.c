/* The project's H3_HAS_AVX2 / H3_HAS_AVX512 macros are defined as CMake
 * target compile definitions on the whole `h3` library, so they're set
 * for every translation unit — including this one, which is built with
 * the project default flags (no per-file `-mavx2` / `-mavx512f`). The
 * per-file ISA flags only land on files under `src/h3lib/lib/simd/`,
 * applied by `cmake/H3Simd.cmake`.
 *
 * If we entered the `#if defined(H3_HAS_AVX2)` / `#if defined(H3_HAS_AVX512)`
 * blocks below in a TU that wasn't compiled with the corresponding ISA
 * flag, GCC fires `-Wpsabi` on functions whose signatures contain AVX
 * vector returns, AND fails to inline `_mm512_*` `always_inline`
 * intrinsics with "target specific option mismatch". CI runs with
 * `-Werror` so both become hard build failures.
 *
 * Force-cancel the project macros for THIS TU when the compiler-set
 * predefines say the ISA isn't actually enabled here. Inside SIMD
 * source files (where the per-file flag is in effect), `__AVX2__` /
 * `__AVX512F__` are defined and the project macros stay enabled. */
#if defined(H3_HAS_AVX2) && !defined(__AVX2__)
#undef H3_HAS_AVX2
#endif
#if defined(H3_HAS_AVX512) && !defined(__AVX512F__)
#undef H3_HAS_AVX512
#endif

