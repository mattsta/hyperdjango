/** square root of 7 and inverse square root of 7 */
#define M_SQRT7 2.6457513110645905905016157536392604257102
#define M_RSQRT7 0.37796447300922722721451653623418006081576

/* Powers of M_RSQRT7 for resolution scaling in _hex2dToVec3. The original
 * code spun a `for (i=0; i<res; i++) r *= M_RSQRT7` loop on every call;
 * this lookup replaces that 0..15-iteration multiply chain with a single
 * load. Index 16 covers the substrate-classIII path which needs
 * M_RSQRT7^(res+1) at res=15. Constant-folded at compile time via the
 * pow-of-two macro decomposition. */
#define _R1 M_RSQRT7
#define _R2 (_R1 * _R1)
#define _R4 (_R2 * _R2)
#define _R8 (_R4 * _R4)
#define _R16 (_R8 * _R8)
static const double RSQRT7_POW[17] = {
    1.0,                  /* ^0  */
    _R1,                  /* ^1  */
    _R2,                  /* ^2  */
    _R2 *_R1,             /* ^3  */
    _R4,                  /* ^4  */
    _R4 *_R1,             /* ^5  */
    _R4 *_R2,             /* ^6  */
    _R4 * _R2 * _R1,      /* ^7  */
    _R8,                  /* ^8  */
    _R8 *_R1,             /* ^9  */
    _R8 *_R2,             /* ^10 */
    _R8 * _R2 * _R1,      /* ^11 */
    _R8 *_R4,             /* ^12 */
    _R8 * _R4 * _R1,      /* ^13 */
    _R8 * _R4 * _R2,      /* ^14 */
    _R8 * _R4 * _R2 *_R1, /* ^15 */
    _R16,                 /* ^16 */
};
#undef _R1
#undef _R2
#undef _R4
#undef _R8
#undef _R16

